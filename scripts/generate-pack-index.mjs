import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const packs = readdirSync(resolve(root, "dsh-pet/assets/pets"), {
  withFileTypes: true,
})
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()
  .filter((id) => {
    try {
      readFileSync(resolve(root, `dsh-pet/assets/pets/${id}/pet.json`));
      return true;
    } catch {
      return false;
    }
  });
for (const id of packs) {
  const base = resolve(root, "dsh-pet/assets/pets", id),
    p = JSON.parse(readFileSync(resolve(base, "pet.json"), "utf8"));
  if (!/^[a-z][a-z0-9-]{0,63}$/.test(id) || p.id !== id)
    throw Error("Role directory must match manifest id: " + id);
  for (const action of p.actions) {
    if (
      !/^(images|webm)\/[^\\/:*?"<>|\x00-\x1f]+\.(png|webp|webm)$/.test(
        action.file,
      ) ||
      action.file.includes("..")
    )
      throw Error("Unsafe asset path: " + action.file);
    if (!existsSync(resolve(base, action.file)))
      throw Error("Missing asset: " + id + "/" + action.file);
  }
}
writeFileSync(
  resolve(root, "dsh-pet/src/shared/generated-packs.ts"),
  "// Generated by scripts/generate-pack-index.mjs; edit pet.json files, not this file.\n" +
    packs
      .map(
        (id, i) =>
          `import pack${i} from '../../assets/pets/${id}/pet.json' with { type: 'json' };`,
      )
      .join("\n") +
    `\nexport const builtinPacks = [${packs.map((_, i) => "pack" + i).join(", ")}];\n`,
);
console.log(`Indexed ${packs.length} PetPacks: ${packs.join(", ")}`);
